PHRASES.sort(key=lambda x: len(x[0]), reverse=True)
WORDS.sort(key=lambda x: len(x[0]), reverse=True)
WORD_PATS = [(re.compile(r"(?<!\w)" + re.escape(fr) + r"(?!\w)"), en) for fr, en in WORDS]


def translate_text(text: str) -> str:
    out = text
    for fr, en in PHRASES:
        if fr in out:
            out = out.replace(fr, en)
    for pat, en in WORD_PATS:
        if pat.search(out):
            out = pat.sub(en, out)
    return out


def process_file(path: Path) -> int:
    text = path.read_text(encoding="utf-8")
    for old, new in IDENT:
        text = text.replace(old, new)
    for _ in range(15):
        if not ACCENT.search(text):
            break
        lines = text.splitlines(keepends=True)
        text = "".join(translate_text(l) if ACCENT.search(l) else l for l in lines)
    path.write_text(text, encoding="utf-8")
    return len(ACCENT.findall(text))


