package distrib

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"net/http"
	"net/url"
	"strings"
)

func digestOf(data []byte) string {
	var h = sha256.Sum256(data)
	return "sha256:" + hex.EncodeToString(h[:])
}

// externalBase returns the controller's public URL: configured if set,
// otherwise derived from the request (scheme + Host).
func (s *Service) externalBase(r *http.Request) *url.URL {
	if s.Cfg.ExternalURL != "" {
		var u, err = url.Parse(strings.TrimSuffix(s.Cfg.ExternalURL, "/"))
		if err == nil && u.Host != "" {
			return u
		}
	}
	var scheme = "http"
	if r.TLS != nil || r.Header.Get("X-Forwarded-Proto") == "https" {
		scheme = "https"
	}
	return &url.URL{Scheme: scheme, Host: r.Host}
}

// PublicURL returns the controller's public URL as a proxy must contact it
// (configured if set, otherwise derived from the request).
func (s *Service) PublicURL(r *http.Request) string {
	return s.externalBase(r).String()
}

// ImageRef returns the proxy's image reference in the embedded registry,
// e.g. ctrl.example.com:8080/meshcraft/proxy:latest
func (s *Service) ImageRef(r *http.Request) string {
	return s.externalBase(r).Host + "/" + proxyRepo + ":latest"
}

// InsecureNote reports the insecure-registries configuration needed over HTTP.
func (s *Service) InsecureNote(r *http.Request) string {
	var base = s.externalBase(r)
	if base.Scheme == "https" {
		return ""
	}
	return fmt.Sprintf(
		`The controller is served over HTTP: add {"insecure-registries":["%s"]} to /etc/docker/daemon.json on the proxy host (then systemctl restart docker) to allow the pull.`,
		base.Host)
}

// ComposeYAML generates the proxy's docker-compose: the image is pulled from
// the controller's embedded registry, and the controller URL and enrollment
// token are pre-filled.
func (s *Service) ComposeYAML(r *http.Request, enrollToken string) string {
	var base = s.externalBase(r)
	var b strings.Builder
	b.WriteString("# meshcraft proxy — generated by controller " + base.String() + "\n")
	b.WriteString("# The image is pulled from the controller's embedded registry.\n")
	if s.InsecureNote(r) != "" {
		b.WriteString("# NOTE: " + s.InsecureNote(r) + "\n")
	}
	b.WriteString("services:\n")
	b.WriteString("  meshcraft-proxy:\n")
	b.WriteString("    image: " + s.ImageRef(r) + "\n")
	b.WriteString("    restart: unless-stopped\n")
	b.WriteString("    # host: required for ARP/ND scans and for receiving\n")
	b.WriteString("    # syslog/traps on the local networks reachable by this host.\n")
	b.WriteString("    # In bridge mode, the messages' source IP would be the Docker\n")
	b.WriteString("    # gateway's, making it impossible to attribute a message to a device.\n")
	b.WriteString("    network_mode: host\n")
	b.WriteString("    cap_add:\n")
	b.WriteString("      - NET_RAW              # ARP / Neighbor Discovery scan\n")
	b.WriteString("      - NET_BIND_SERVICE     # syslog 514/udp, traps 162/udp\n")
	b.WriteString("    environment:\n")
	b.WriteString("      MESHCRAFT_CONTROLLER: \"" + base.String() + "\"\n")
	b.WriteString("      MESHCRAFT_ENROLL_TOKEN: \"" + enrollToken + "\"\n")
	b.WriteString("    volumes:\n")
	b.WriteString("      - meshcraft_proxy_state:/var/lib/meshcraft\n")
	b.WriteString("volumes:\n")
	b.WriteString("  meshcraft_proxy_state:\n")
	return b.String()
}
