-- Credential notes written while the controller still spoke French.
-- Source already emits English (pwpolicy_creds.go); this rewrites rows that
-- still carry the old sentence so the credentials screen stops showing French
-- on an English UI.
update site_credentials
   set note = regexp_replace(
     note,
     '^Mot de passe d''administration engendré par meshcraft pour les équipements dont la politique impose ([0-9]+) caractères \(étiquette technique, posée automatiquement\)\. Le secret du site ne tient pas dans les bornes de ces plateformes : leur connecteur le refuse avant de l''envoyer\. Cet identifiant n''est ni modifiable ni supprimable à la main — c''est meshcraft qui le gère\.$',
     'Administration password generated by meshcraft for devices whose policy requires \1 characters (technical tag, set automatically). The site secret does not fit these platforms'' bounds: their connector refuses it before sending. This credential is neither editable nor deletable by hand — meshcraft manages it.'
   )
 where note like 'Mot de passe d''administration engendré%';
