package api

import (
	"context"
	"log/slog"

	"meshcraft/internal/model"
	"meshcraft/internal/pwgen"
	"meshcraft/internal/secretbox"
	"meshcraft/internal/store"
)

// Default site administration credential.
//
// A site without a credential is a site where meshcraft cannot apply anything:
// the operator's first action would be to create one, and until they do, every
// adopted device keeps its factory password — i.e. often NONE. The safe default
// is therefore to create it ourselves, not to demand it.

// EnsureSiteAdminCredential creates a site's default administration credential
// if it does not have one.
//
// Idempotent: called at site creation AND at controller startup to backfill
// existing sites. Returns `created` so the caller knows whether to log it — a
// silent backfill that stores secrets is exactly the kind of event you regret
// not finding afterward.
func EnsureSiteAdminCredential(ctx context.Context, st *store.Store, secrets *secretbox.Service,
	siteID, actorID string) (bool, error) {
	var creds, err = st.ListSiteCredentials(ctx, siteID)
	if err != nil {
		return false, err
	}
	var c model.SiteCredential
	for _, c = range creds {
		// A default credential already exists: do not touch it. Overwriting an
		// in-service site's secret would cut meshcraft off from its own fleet.
		if c.GroupName == "" && c.Kind == "admin" {
			return false, nil
		}
	}

	var secret string
	secret, err = pwgen.New(pwgen.DefaultLength)
	if err != nil {
		return false, err
	}
	var enc []byte
	enc, err = secrets.Seal(secret)
	if err != nil {
		return false, err
	}
	// The desired name is `mcadmin`; what actually lands on a device depends on
	// its connector (many only accept `admin`), and it is the ACTUALLY applied
	// name that gets recorded per device.
	_, err = st.UpsertSiteCredential(ctx, model.SiteCredential{
		SiteID: siteID, GroupName: "", Kind: "admin",
		Username: pwgen.DefaultUsername,
		Note:     "Generated by meshcraft at site creation — 16 alphanumeric characters.",
		// No second line: an administration password has only one secret.
		// Only an SNMPv3 identity carries two (migration 0017).
	}, enc, nil, actorID)
	if err != nil {
		return false, err
	}
	return true, nil
}

// BackfillSiteCredentials gives existing sites a default credential.
// Called once at startup. A site that already has one is left as-is.
func BackfillSiteCredentials(ctx context.Context, st *store.Store, secrets *secretbox.Service) error {
	var sites, err = st.ListSites(ctx, "", true)
	if err != nil {
		return err
	}
	var site model.Site
	for _, site = range sites {
		var created bool
		created, err = EnsureSiteAdminCredential(ctx, st, secrets, site.ID, "")
		if err != nil {
			return err
		}
		if created {
			// Logged in the database so the operator can find WHEN the secret
			// appeared, not just that it exists.
			var evErr = st.InsertEvent(ctx, model.Event{
				SiteID: &site.ID, Type: "credential.generated", Severity: model.SevNotice,
				Actor: "meshcraft",
				Message: "Administration credential generated for \"" + site.Name +
					"\" — 16-character password, reveal from Configuration -> Credentials.",
			})
			if evErr != nil {
				return evErr
			}
			slog.Info("site credential generated", "site", site.Name)
		}
	}
	return nil
}
