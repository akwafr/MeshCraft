// Package pwgen generates secrets that meshcraft sets on devices itself.
//
// Alphabet choice is not aesthetic: it is dictated by the fleet. Switch admin
// interfaces reject, depending on model, spaces, quotes, ampersands, semicolons
// — and some silently truncate beyond a length they do not advertise. A purely
// ALPHANUMERIC secret crosses the entire fleet without exception, and that
// matters more than a few extra entropy bits: a password rejected by half the
// devices protects nothing.
//
// 16 characters in an alphabet of 62 yield ~95 bits. Against a switch web
// interface that accepts only a few tries per second, the margin is comfortable.
package pwgen

import (
	"crypto/rand"
	"errors"
	"fmt"
	"strings"
)

// Alphabet: uppercase, lowercase, digits. Nothing else — see header.
//
// This constant is the ONLY place that decides what a meshcraft secret contains,
// and other decisions now depend on it: the password-policy technical tag
// (internal/pwpolicy) does NOT name a platform's "alphanumeric only" constraint,
// precisely because everything produced here already satisfies it. The day this
// alphabet gains punctuation, that deduction falls — hence the test that locks
// its content, not only the content of drawn secrets.
const Alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"

// DefaultLength is the length of secrets generated by meshcraft.
const DefaultLength = 16

// MinLength is the ABSOLUTE floor: below it, generating a secret would give a
// false sense of security. A platform that would not accept eight characters is
// not provisionable by meshcraft, and that is a frank refusal — not a silently
// shortened secret.
const MinLength = 8

// DefaultUsername is the account meshcraft tries to set. "Ideally": many entry-
// level switches admit no admin account other than `admin`. The connector decides
// via its capabilities, and the name ACTUALLY set is recorded per device —
// never the one we hoped for.
const DefaultUsername = "mcadmin"

// ErrTooShort: below MinLength characters, generating a secret would give a false
// sense of security. We refuse rather than allow it.
var ErrTooShort = errors.New("secret too short")

// Length decides draw length under PLATFORM bounds, and explicitly refuses a
// constraint we cannot satisfy.
//
// Bounds come from [driver.AdminAccount] (`PasswordMin` / `PasswordMax`), where
// 0 means "unknown, therefore unconstrained". What follows is the project's only
// rule on the subject, and it lives HERE because two places depend on it: secret
// generation, and the technical tag name that carries it (internal/pwpolicy).
// Two length calculations means a day when the tag says 15 and the secret is 16 —
// an identifier stored under a lying name, and a fleet cut in two.
//
// Rule: aim for DefaultLength, come down to the platform ceiling, come up to its
// floor.
//
// FAILURE RATHER THAN A TRUNCATED SECRET, in both cases where bounds cannot be
// satisfied:
//
//   - floor above ceiling: the platform contradicts itself (or the capability
//     was misread). Drawing "as close as possible" would set a secret the device
//     rejects, after writing — i.e. at the worst moment;
//   - ceiling below MinLength: a six-character secret on infrastructure gear is
//     not a compromise, it is an open door believed closed.
func Length(min, max int) (int, error) {
	if min < 0 || max < 0 {
		return 0, fmt.Errorf("negative password bounds (min %d, max %d): "+
			"connector capability is wrong", min, max)
	}
	if max > 0 && min > max {
		return 0, fmt.Errorf("contradictory password bounds: device would require "+
			"at least %d characters but accept at most %d — no secret satisfies both",
			min, max)
	}
	var n = DefaultLength
	if max > 0 && n > max {
		n = max
	}
	if n < min {
		n = min
	}
	if n < MinLength {
		return 0, fmt.Errorf("%w: device accepts only %d characters, and meshcraft "+
			"generates nothing below %d — a shorter secret would protect less than "+
			"it would suggest",
			ErrTooShort, max, MinLength)
	}
	return n, nil
}

// NewBounded generates a secret that fits platform bounds.
//
// This is the provisioning entry point when device policy is not site policy: on
// MikroTik SwOS, capped at 15 characters, the 16-character site secret is
// rejected by the connector BEFORE send — correct behavior, but leaves the device
// without a settable password until someone generates at the right length.
func NewBounded(min, max int) (string, error) {
	var n, err = Length(min, max)
	if err != nil {
		return "", err
	}
	return New(n)
}

// New generates an n-character secret.
//
// Drawing is UNBIASED: 62 does not divide 256, a simple `byte % 62` would favor
// the first 8 letters of the alphabet. Bytes ≥ 248 are therefore rejected and
// discarded.
//
// The result contains at least one lowercase, one uppercase, and one digit: some
// devices require that composition, and a secret rejected at apply time costs a
// field round trip.
func New(n int) (string, error) {
	if n < MinLength {
		return "", ErrTooShort
	}
	var attempt int
	for attempt = 0; attempt < 100; attempt++ {
		var s, err = draw(n)
		if err != nil {
			return "", err
		}
		if strings.ContainsAny(s, "abcdefghijklmnopqrstuvwxyz") &&
			strings.ContainsAny(s, "ABCDEFGHIJKLMNOPQRSTUVWXYZ") &&
			strings.ContainsAny(s, "0123456789") {
			return s, nil
		}
	}
	// Unreachable in practice (probability of failing 100 times in a row is on the
	// order of 10^-90), but a loop without exit is an outage that only appears in
	// production.
	return "", errors.New("draw failed")
}

// draw draws n characters from the alphabet, without modulo bias.
func draw(n int) (string, error) {
	// 248 = 62 × 4: largest multiple of 62 fitting in a byte.
	const limit = 248
	var out = make([]byte, 0, n)
	// Draw generously to limit round trips to the generator: about 3% of bytes
	// are rejected.
	var buf = make([]byte, n+n/4+8)
	for len(out) < n {
		var _, err = rand.Read(buf)
		if err != nil {
			return "", err
		}
		var b byte
		for _, b = range buf {
			if b >= limit {
				continue
			}
			out = append(out, Alphabet[int(b)%len(Alphabet)])
			if len(out) == n {
				break
			}
		}
	}
	return string(out), nil
}
